#!/usr/bin/env bash
# Sync Supabase URL + anon key from repo .env into android-overlay/local.properties
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="$ROOT/.env"
OUT="$ROOT/android-overlay/local.properties"
EXAMPLE="$ROOT/android-overlay/local.properties.example"

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Missing $ENV_FILE — copy .env.example and fill values."
  exit 1
fi

URL="$(grep -E '^VITE_SUPABASE_URL=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '\r' | sed 's/^"//;s/"$//')"
KEY="$(grep -E '^VITE_SUPABASE_ANON_KEY=' "$ENV_FILE" | head -1 | cut -d= -f2- | tr -d '\r' | sed 's/^"//;s/"$//')"

if [[ -z "$URL" || -z "$KEY" ]]; then
  echo "VITE_SUPABASE_URL / VITE_SUPABASE_ANON_KEY missing in .env"
  exit 1
fi

SDK_LINE=""
if [[ -f "$OUT" ]] && grep -q '^sdk.dir=' "$OUT"; then
  SDK_LINE="$(grep '^sdk.dir=' "$OUT" | head -1)"
elif [[ -d "${ANDROID_HOME:-}" ]]; then
  SDK_LINE="sdk.dir=${ANDROID_HOME}"
elif [[ -d "$HOME/Android/Sdk" ]]; then
  SDK_LINE="sdk.dir=$HOME/Android/Sdk"
fi

{
  echo "# Generated by scripts/sync-supabase-config.sh — do not commit secrets"
  [[ -n "$SDK_LINE" ]] && echo "$SDK_LINE"
  echo "supabase.url=$URL"
  echo "supabase.anonKey=$KEY"
} > "$OUT"

echo "Wrote $OUT"
echo "Example template remains at $EXAMPLE"
